-- AI Companion minimal schema (no auth.uid usage)
-- Requires pgvector extension
CREATE EXTENSION IF NOT EXISTS vector;

-- Core chat table
CREATE TABLE IF NOT EXISTS ai_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('user','assistant','system')),
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- simple foreign-key like check without RLS dependency
  CONSTRAINT fk_user_exists CHECK (EXISTS (SELECT 1 FROM users u WHERE u.id = user_id))
);

-- Memories table with vector embeddings
CREATE TABLE IF NOT EXISTS ai_memories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL,
  memory_kind TEXT NOT NULL CHECK (memory_kind IN ('like','dislike','hobby','movie','song','trait','life_update','generic')),
  content TEXT NOT NULL,
  embedding VECTOR(1536), -- adjust to chosen embedding size
  importance SMALLINT DEFAULT 1 CHECK (importance BETWEEN 1 AND 5),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_user_exists_mem CHECK (EXISTS (SELECT 1 FROM users u WHERE u.id = user_id))
);

